import { getColumnDisplayType } from "./ColumnDisplay";
import { isDateLikeColumnType } from "./DateTimeFormat";
import { isObsidianTagsKey, toBooleanValue } from "./ColumnTypes";
import { t } from "../i18n";
import { ColumnDef, ComputedFieldDef, FilterRule, ViewConfig } from "./types";

export function isEffectiveFilterRule(rule: FilterRule, validFields?: Set<string>): boolean {
  if (!rule?.field) return false;
  if (validFields && !validFields.has(rule.field)) return false;
  if (rule.op === "empty" || rule.op === "notempty") return true;
  return String(rule.value ?? "").trim().length > 0;
}

export function getEffectiveFilterRules(rules: FilterRule[] | undefined, validFields?: Set<string>): FilterRule[] {
  return (rules || []).filter((rule) => isEffectiveFilterRule(rule, validFields));
}

export function getFilterOperatorsForColumn(col?: ColumnDef, computedFields?: ComputedFieldDef[]): [FilterRule["op"], string][] {
  const type = col ? getColumnDisplayType(col, computedFields) : undefined;
  const base: [FilterRule["op"], string][] = [
    ["eq", t("filter.eq")],
    ["neq", t("filter.neq")],
  ];
  const emptyOps: [FilterRule["op"], string][] = [
    ["empty", t("filter.empty")],
    ["notempty", t("filter.notempty")],
  ];
  if (!col) return [...base, ["contains", t("filter.contains")], ...emptyOps];
  if (type === "number" || type === "currency" || isDateLikeColumnType(type)) {
    return [...base, ["gt", t("filter.gt")], ["gte", t("filter.gte")], ["lt", t("filter.lt")], ["lte", t("filter.lte")], ...emptyOps];
  }
  if (type === "select" || type === "status") {
    return [...base, ["gt", t("filter.gt")], ["gte", t("filter.gte")], ["lt", t("filter.lt")], ["lte", t("filter.lte")], ...emptyOps];
  }
  if (type === "multi-select") {
    if (col.key === "file.tags" || isObsidianTagsKey(col.key)) return [...base, ["hasTag", t("filter.hasTag")], ["contains", t("filter.contains")], ...emptyOps];
    return [...base, ["contains", t("filter.contains")], ...emptyOps];
  }
  if (type === "checkbox") {
    return [["notempty", t("filter.checkboxChecked")], ["empty", t("filter.checkboxUnchecked")]];
  }
  return [...base, ["contains", t("filter.contains")], ...emptyOps];
}

/** Display a legacy checkbox comparison without rewriting the saved rule. */
export function getPresentedFilterOperator(rule: FilterRule, column?: ColumnDef, computedFields?: ComputedFieldDef[]): FilterRule["op"] {
  if (rule.comparison !== "legacy" && column && getColumnDisplayType(column, computedFields) === "checkbox" && (rule.op === "eq" || rule.op === "neq")) {
    const checked = toBooleanValue(rule.value);
    return (rule.op === "eq" ? checked : !checked) ? "notempty" : "empty";
  }
  return rule.op;
}

/** Offer current, type-appropriate choices while keeping any saved legacy operator selectable. */
export function getFilterEditorOperators(column: ColumnDef | undefined, computedFields: ComputedFieldDef[] | undefined,
  saved: FilterRule["op"]): [FilterRule["op"], string][] {
  const operators = getFilterOperatorsForColumn(column, computedFields);
  return operators.some(([op]) => op === saved) ? operators : [...operators, [saved, t(`filter.${saved}`)]];
}

/** Saved before rule comparison modes existed, or newly generated by this version. */
export function copyPersistedFilters(value: unknown, fallback: "legacy" | "typed" = "legacy"): FilterRule[] | undefined {
  if (!Array.isArray(value)) return;
  return (value as FilterRule[]).filter(rule => rule && typeof rule === "object")
    .map(rule => ({ ...rule, comparison: rule.comparison === "typed" || rule.comparison === "legacy" || rule.comparison === "chart-label" ? rule.comparison : fallback }));
}

export function copyPersistedViewStates(value: unknown, fallback: "legacy" | "typed"): ViewConfig["viewStates"] {
  if (!value || typeof value !== "object" || Array.isArray(value)) return;
  return Object.fromEntries(Object.entries(value as Record<string, unknown>).flatMap(([mode, state]) => {
    if (!state || typeof state !== "object" || Array.isArray(state)) return [];
    const stored = state as Record<string, unknown>;
    return [[mode, { ...stored, filters: copyPersistedFilters(stored.filters, fallback) }]];
  }));
}
